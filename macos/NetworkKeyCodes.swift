// Physical macOS virtual key codes paired with Windows Set 1 make codes.
// The 0x100 bit represents an extended (E0) Windows key.
internal enum NetworkKeyCodes {
    private static let pairs: [(UInt16, UInt16)] = [
        (0x00, 0x1E), // A
        (0x01, 0x1F), // S
        (0x02, 0x20), // D
        (0x03, 0x21), // F
        (0x04, 0x23), // H
        (0x05, 0x22), // G
        (0x06, 0x2C), // Z
        (0x07, 0x2D), // X
        (0x08, 0x2E), // C
        (0x09, 0x2F), // V
        (0x0B, 0x30), // B
        (0x0C, 0x10), // Q
        (0x0D, 0x11), // W
        (0x0E, 0x12), // E
        (0x0F, 0x13), // R
        (0x10, 0x15), // Y
        (0x11, 0x14), // T
        (0x12, 0x02), // 1
        (0x13, 0x03), // 2
        (0x14, 0x04), // 3
        (0x15, 0x05), // 4
        (0x16, 0x07), // 6
        (0x17, 0x06), // 5
        (0x18, 0x0D), // Equals
        (0x19, 0x0A), // 9
        (0x1A, 0x08), // 7
        (0x1B, 0x0C), // Minus
        (0x1C, 0x09), // 8
        (0x1D, 0x0B), // 0
        (0x1E, 0x1B), // Right bracket
        (0x1F, 0x18), // O
        (0x20, 0x16), // U
        (0x21, 0x1A), // Left bracket
        (0x22, 0x17), // I
        (0x23, 0x19), // P
        (0x24, 0x1C), // Return
        (0x25, 0x26), // L
        (0x26, 0x24), // J
        (0x27, 0x28), // Quote
        (0x28, 0x25), // K
        (0x29, 0x27), // Semicolon
        (0x2A, 0x2B), // Backslash
        (0x2B, 0x33), // Comma
        (0x2C, 0x35), // Slash
        (0x2D, 0x31), // N
        (0x2E, 0x32), // M
        (0x2F, 0x34), // Period
        (0x30, 0x0F), // Tab
        (0x31, 0x39), // Space
        (0x32, 0x29), // Grave
        (0x33, 0x0E), // Backspace
        (0x35, 0x01), // Escape
        (0x36, 0x15C), // Right Command / Windows
        (0x37, 0x15B), // Left Command / Windows
        (0x38, 0x2A), // Left Shift
        (0x39, 0x3A), // Caps Lock
        (0x3A, 0x38), // Left Option / Alt
        (0x3B, 0x1D), // Left Control
        (0x3C, 0x36), // Right Shift
        (0x3D, 0x138), // Right Option / Alt
        (0x3E, 0x11D), // Right Control
        (0x41, 0x53), // Keypad decimal
        (0x43, 0x37), // Keypad multiply
        (0x45, 0x4E), // Keypad plus
        (0x47, 0x45), // Keypad clear / Num Lock
        (0x4B, 0x135), // Keypad divide
        (0x4C, 0x11C), // Keypad Enter
        (0x4E, 0x4A), // Keypad minus
        (0x52, 0x52), // Keypad 0
        (0x53, 0x4F), // Keypad 1
        (0x54, 0x50), // Keypad 2
        (0x55, 0x51), // Keypad 3
        (0x56, 0x4B), // Keypad 4
        (0x57, 0x4C), // Keypad 5
        (0x58, 0x4D), // Keypad 6
        (0x59, 0x47), // Keypad 7
        (0x5B, 0x48), // Keypad 8
        (0x5C, 0x49), // Keypad 9
        (0x60, 0x3F), // F5
        (0x61, 0x40), // F6
        (0x62, 0x41), // F7
        (0x63, 0x3D), // F3
        (0x64, 0x42), // F8
        (0x65, 0x43), // F9
        (0x67, 0x57), // F11
        (0x69, 0x64), // F13
        (0x6A, 0x67), // F16
        (0x6B, 0x65), // F14
        (0x6D, 0x44), // F10
        (0x6E, 0x15D), // Menu
        (0x6F, 0x58), // F12
        (0x71, 0x66), // F15
        (0x72, 0x152), // Help / Insert
        (0x73, 0x147), // Home
        (0x74, 0x149), // Page Up
        (0x75, 0x153), // Forward Delete
        (0x76, 0x3E), // F4
        (0x77, 0x14F), // End
        (0x78, 0x3C), // F2
        (0x79, 0x151), // Page Down
        (0x7A, 0x3B), // F1
        (0x7B, 0x14B), // Left
        (0x7C, 0x14D), // Right
        (0x7D, 0x150), // Down
        (0x7E, 0x148) // Up
    ]

    private static let scans = Dictionary(uniqueKeysWithValues: pairs)
    private static let keyCodes = Dictionary(uniqueKeysWithValues: pairs.map { ($0.1, $0.0) })

    static func scan(for keyCode: UInt16) -> UInt16? {
        scans[keyCode]
    }

    static func keyCode(for scan: UInt16) -> UInt16? {
        keyCodes[scan]
    }
}
